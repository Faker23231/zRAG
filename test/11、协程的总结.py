import asyncio
from asyncio import create_task, gather  # 创建并发协程任务 传递协程对象

# 3、协程的使用run
# 本质是开启事件循环，传入要开始循环的协程对象
# 协程必须先run开启事件循环
async def get_url(url):
    print("开始请求")
    # 模拟异步操作，比如网络请求
    await asyncio.sleep(2)  # 模拟耗时操作
    return f"获取到{url}请求的状态"

async def main(urls):
    #主协程主要是来包装协程任务，通过gather一起执行
    list1 = [get_url(url) for url in urls] #协程对象列表（多协程）

    list2 = [create_task(c) for c in list1] #并发协程任务列表

    result = await gather(*list2) #并发执行协程任务，收集结果，返回列表结果顺序传递参数的顺序一样
    return result


