# http 是超文本传输协议 是一个应用层协议 基于底层tcp的协议。
# 协议是规矩规范 http协议规定了客户端与服务端通信的规则，通信的时候咱们俩传递啥东西
# http协议最终发送和返回的就是报文，报文是一坨字符串，分为：  行 头 空行 体


#报文当中包含很多信息：某些信息是我们做前后端的时候必须要掌握的
#作为前后端人员我们其实对报文最原始的样子不太关心，我们关心的是前后端给我们解析的报文当中的重要信息



# 前端
# 1、请求路径
# 2、请求方式
# 3、请求参数
# 4、请求头当中的一些信息（token）
# 5、响应状态和数据（100，200,300,400,500）


# 后端
# 1、接啥  参数（路径 查询 请求体） 请求头  请求方式
# 2、返啥  json数据  文件  流式。。。。





















